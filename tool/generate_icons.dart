// Generates the Phosphor icon constants and the searchable icon catalog.
//
// Usage: dart run tool/generate_icons.dart [phosphor-web/src] [phosphor-core/src/icons.ts]
import 'dart:io';

const _defaultWeb = '../.research/phosphor-web/src';
const _defaultCore = '../.research/phosphor-core/icons.ts';

void main(List<String> args) {
  final web = args.isNotEmpty ? args[0] : _defaultWeb;
  final core = args.length > 1 ? args[1] : _defaultCore;
  final regular = _codepoints(File('$web/regular/style.css').readAsStringSync(), r'\.ph\.ph-');
  final fill = _codepoints(File('$web/fill/style.css').readAsStringSync(), r'\.ph-fill\.ph-');
  final meta = _metadata(File(core).readAsStringSync());

  final names = regular.keys.toList()..sort();
  final dartNames = <String, String>{};
  for (final n in names) {
    final d = _camel(n);
    if (dartNames.containsValue(d) || dartNames.containsValue('${d}Fill')) throw StateError('Name clash: $d');
    dartNames[n] = d;
  }
  for (final n in names) {
    if (dartNames.containsValue('${dartNames[n]}Fill')) throw StateError('Fill clash: $n');
  }

  final icons = StringBuffer()
    ..writeln('// GENERATED by tool/generate_icons.dart from Phosphor Icons ${_version(web)}. Do not edit.')
    ..writeln('// Phosphor Icons, MIT, Copyright (c) 2020-2021 Phosphor Icons. See assets/licenses/Phosphor-MIT.txt.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('/// The ${names.length} Phosphor icons Kumo uses, in regular and fill weights.')
    ..writeln('///')
    ..writeln('/// Regular is the default weight across Kumo. Use the `Fill` twin for a')
    ..writeln('/// selected or active state (a filled star for a starred item).')
    ..writeln('///')
    ..writeln('/// ```dart')
    ..writeln('/// KumoIcon(KumoIcons.gear)')
    ..writeln('/// KumoIcon(KumoIcons.starFill, color: KumoColor.warning)')
    ..writeln('/// ```')
    ..writeln('///')
    ..writeln('/// Every constant is a const [IconData], so release builds tree-shake the')
    ..writeln('/// font down to the glyphs an app actually uses.')
    ..writeln('abstract final class KumoIcons {')
    ..writeln("  static const String _regular = 'Phosphor';")
    ..writeln("  static const String _fill = 'PhosphorFill';")
    ..writeln("  static const String _package = 'kumo_flutter';")
    ..writeln();
  for (final n in names) {
    final d = dartNames[n]!;
    final tags = meta[n]?.tags.where((t) => !t.startsWith('*')).take(6).join(', ');
    icons.writeln('  /// `$n`${tags == null || tags.isEmpty ? '' : ': $tags'}.');
    icons.writeln(
      '  static const IconData $d = IconData(0x${regular[n]!.toRadixString(16)}, fontFamily: _regular, fontPackage: _package);',
    );
    if (fill.containsKey(n)) {
      icons.writeln('  /// `$n`, fill weight.');
      icons.writeln(
        '  static const IconData ${d}Fill = IconData(0x${fill[n]!.toRadixString(16)}, fontFamily: _fill, fontPackage: _package);',
      );
    }
  }
  icons.writeln('}');
  File('lib/src/icons/kumo_icons.g.dart').writeAsStringSync(icons.toString());

  final catalog = StringBuffer()
    ..writeln('// GENERATED by tool/generate_icons.dart. Do not edit.')
    ..writeln()
    ..writeln('/// Searchable catalog of every Kumo icon with Phosphor categories and tags.')
    ..writeln('///')
    ..writeln('/// Kept out of the main library on purpose: importing it references every')
    ..writeln('/// glyph, which turns off icon tree shaking. Use it in icon pickers and')
    ..writeln('/// developer tools, not in production screens.')
    ..writeln('library;')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln("import 'package:kumo_flutter/kumo_flutter.dart';")
    ..writeln()
    ..writeln('/// One icon in the catalog.')
    ..writeln('class KumoIconEntry {')
    ..writeln(
      '  const KumoIconEntry(this.name, this.regular, this.fill, {this.categories = const [], this.tags = const []});',
    )
    ..writeln()
    ..writeln('  /// Phosphor kebab-case name, such as `caret-down`.')
    ..writeln('  final String name;')
    ..writeln('  final IconData regular;')
    ..writeln('  final IconData? fill;')
    ..writeln('  final List<String> categories;')
    ..writeln('  final List<String> tags;')
    ..writeln()
    ..writeln('  /// True when [query] matches the name, a tag or a category.')
    ..writeln('  bool matches(String query) {')
    ..writeln('    final q = query.trim().toLowerCase();')
    ..writeln('    if (q.isEmpty) return true;')
    ..writeln(
      "    return name.contains(q.replaceAll(' ', '-')) || tags.any((t) => t.contains(q)) || categories.any((c) => c.contains(q));",
    )
    ..writeln('  }')
    ..writeln('}')
    ..writeln()
    ..writeln('/// All ${names.length} icons, sorted by name.')
    ..writeln('const List<KumoIconEntry> kumoIconCatalog = [');
  String list(List<String> v) => '[${v.map((e) => "'${e.replaceAll("'", r"\'")}'").join(', ')}]';
  for (final n in names) {
    final d = dartNames[n]!;
    final m = meta[n];
    catalog.writeln(
      "  KumoIconEntry('$n', KumoIcons.$d, ${fill.containsKey(n) ? 'KumoIcons.${d}Fill' : 'null'}"
      "${m == null ? '' : ', categories: ${list(m.categories)}, tags: ${list(m.tags.where((t) => !t.startsWith('*')).toList())}'}),",
    );
  }
  catalog.writeln('];');
  File('lib/kumo_icon_catalog.dart').writeAsStringSync(catalog.toString());
  stdout.writeln('Wrote ${names.length} icons (${fill.length} fill).');
}

Map<String, int> _codepoints(String css, String prefix) {
  final re = RegExp(prefix + r'([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"');
  return {for (final m in re.allMatches(css)) m.group(1)!: int.parse(m.group(2)!, radix: 16)};
}

class _Meta {
  _Meta(this.categories, this.tags);
  final List<String> categories;
  final List<String> tags;
}

Map<String, _Meta> _metadata(String ts) {
  final result = <String, _Meta>{};
  final entry = RegExp(r'name: "([a-z0-9-]+)",[\s\S]*?categories: \[([^\]]*)\],[\s\S]*?tags: \[([^\]]*)\]');
  for (final m in entry.allMatches(ts)) {
    final cats = RegExp(
      r'IconCategory\.([A-Z_]+)',
    ).allMatches(m.group(2)!).map((c) => c.group(1)!.toLowerCase().replaceAll('_', ' ')).toList();
    final tags = RegExp(r'"([^"]+)"').allMatches(m.group(3)!).map((t) => t.group(1)!.toLowerCase()).toList();
    result.putIfAbsent(m.group(1)!, () => _Meta(cats, tags));
  }
  return result;
}

String _camel(String kebab) {
  final parts = kebab.split('-');
  return parts.first + parts.skip(1).map((p) => p.isEmpty ? '' : p[0].toUpperCase() + p.substring(1)).join();
}

String _version(String web) {
  final pkg = File('$web/../package.json');
  if (!pkg.existsSync()) return '';
  return RegExp(r'"version": "([^"]+)"').firstMatch(pkg.readAsStringSync())?.group(1) ?? '';
}
