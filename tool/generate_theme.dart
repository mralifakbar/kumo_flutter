void main(List<String> args) {
  final dir = args.isEmpty ? _defaultStyles : args.first;
  final kumoCss = File('$dir/theme-kumo.css').readAsStringSync();
  final fedrampCss = File('$dir/theme-fedramp.css').readAsStringSync();

  final light = _parseBlock(kumoCss, RegExp(r':root,\s*\[data-theme="kumo"\]\s*\{'));
  final dark = _parseBlock(kumoCss, RegExp(r':root\[data-mode="dark"\][^{]*\{'));
  final fedrampLight = {
    ...light,
    ..._parseBlock(fedrampCss, RegExp(r'@layer base \{\s*\[data-theme="fedramp"\]\s*\{'), last: true),
  };
  final fedrampDark = {
    ...dark,
    ..._parseBlock(fedrampCss, RegExp(r'\[data-mode="dark"\] \[data-theme="fedramp"\][^{]*\{')),
  };

  final names = light.keys.toList();
  for (final n in names) {
    if (!dark.containsKey(n)) throw StateError('Token $n has no dark value');
    if (!_descriptions.containsKey(n)) throw StateError('Token $n has no description');
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_theme.dart from Kumo theme CSS. Do not edit.')
    ..writeln('// Source: github.com/cloudflare/kumo, MIT. Values are OKLCH gamut-mapped to sRGB.')
    ..writeln()
    ..writeln("import 'dart:ui' show Color;")
    ..writeln()
    ..writeln('/// Kumo semantic color tokens. Text tokens mirror `text-kumo-*` classes,')
    ..writeln('/// the rest mirror `bg-kumo-*`, `ring-kumo-*` and `border-kumo-*`.')
    ..writeln('enum KumoColor {');
  for (final n in names) {
    out
      ..writeln('  /// ${_descriptions[n]}')
      ..writeln('  $n,');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/// A resolved set of Kumo colors for one mode and theme.')
    ..writeln('class KumoColorScheme {')
    ..writeln('  const KumoColorScheme({');
  for (final n in names) {
    out.writeln('    required this.$n,');
  }
  out.writeln('  });');
  out.writeln();
  for (final n in names) {
    out
      ..writeln('  /// ${_descriptions[n]}')
      ..writeln('  final Color $n;');
  }
  out
    ..writeln()
    ..writeln('  /// Looks a token up by enum, for components that take a [KumoColor].')
    ..writeln('  Color operator [](KumoColor token) => switch (token) {');
  for (final n in names) {
    out.writeln('        KumoColor.$n => $n,');
  }
  out
    ..writeln('      };')
    ..writeln()
    ..writeln('  /// Returns a copy with the given tokens replaced.')
    ..writeln('  KumoColorScheme copyWith(Map<KumoColor, Color> overrides) => KumoColorScheme(');
  for (final n in names) {
    out.writeln('        $n: overrides[KumoColor.$n] ?? $n,');
  }
  out
    ..writeln('      );')
    ..writeln()
    ..writeln('  /// Interpolates every token, used to cross-fade a theme change.')
    ..writeln('  static KumoColorScheme lerp(KumoColorScheme a, KumoColorScheme b, double t) => KumoColorScheme(');
  for (final n in names) {
    out.writeln('        $n: Color.lerp(a.$n, b.$n, t)!,');
  }
  out
    ..writeln('      );')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  bool operator ==(Object other) =>')
    ..writeln('      other is KumoColorScheme && KumoColor.values.every((t) => this[t] == other[t]);')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  int get hashCode => Object.hashAll(KumoColor.values.map((t) => this[t]));')
    ..writeln('}')
    ..writeln()
    ..writeln('/// The color schemes Kumo ships.')
    ..writeln('abstract final class KumoColorSchemes {');
  void scheme(String name, String doc, Map<String, int> values) {
    out
      ..writeln('  /// $doc')
      ..writeln('  static const KumoColorScheme $name = KumoColorScheme(');
    for (final n in names) {
      out.writeln('    $n: Color(0x${values[n]!.toRadixString(16).padLeft(8, '0').toUpperCase()}),');
    }
    out.writeln('  );');
  }

  scheme('light', 'Kumo light mode.', light);
  scheme('dark', 'Kumo dark mode.', dark);
  scheme('fedrampLight', 'FedRAMP theme, light mode: slate canvas and base surfaces.', fedrampLight);
  scheme('fedrampDark', 'FedRAMP theme, dark mode.', fedrampDark);
  out.writeln('}');

  File('lib/src/theme/generated/kumo_colors.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote ${names.length} tokens.');
}

Map<String, int> _parseBlock(String css, RegExp start, {bool last = false}) {
  final matches = start.allMatches(css).toList();
  if (matches.isEmpty) throw StateError('Block $start not found');
  final m = last ? matches.last : matches.first;
  final end = css.indexOf('}', m.end);
  final body = css.substring(m.end, end);
  final result = <String, int>{};
  for (final decl in body.split(';')) {
    final idx = decl.indexOf(':');
    if (idx < 0) continue;
    final prop = decl.substring(0, idx).trim();
    if (!prop.startsWith('--')) continue;
    final value = decl
        .substring(idx + 1)
        .replaceAll(RegExp(r'\s+'), ' ')
        .replaceAll('( ', '(')
        .replaceAll(' )', ')')
        .trim();
    result[_tokenName(prop)] = _parseColor(value).toArgb();
  }
  return result;
}

String _tokenName(String prop) {
  String camel(String kebab) {
    final parts = kebab.split('-');
    return parts.first + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
  }

  if (prop.startsWith('--text-color-kumo-')) {
    final rest = camel(prop.substring('--text-color-kumo-'.length));
    return 'text${rest[0].toUpperCase()}${rest.substring(1)}';
  }
  if (prop.startsWith('--color-kumo-')) return camel(prop.substring('--color-kumo-'.length));
  throw StateError('Unknown token $prop');
}

Oklch _parseColor(String value) {
  value = value.trim();
  final varMatch = RegExp(r'^var\(--[a-z0-9-]+,\s*(.*)\)$').firstMatch(value);
  if (varMatch != null) return _parseColor(varMatch.group(1)!);
  if (value == 'transparent') return const Oklch(0, 0, 0, 0);
  if (value.startsWith('#')) {
    var hex = value.substring(1);
    if (hex.length == 3) hex = hex.split('').map((c) => '$c$c').join();
    return Oklch.fromArgb(0xFF000000 | int.parse(hex, radix: 16));
  }
  final mix = RegExp(r'^color-mix\(in oklch, (.*), (black|white) (\d+(?:\.\d+)?)%\)$').firstMatch(value);
  if (mix != null) {
    final base = _parseColor(mix.group(1)!);
    final other = mix.group(2) == 'black' ? const Oklch(0, 0, 0) : const Oklch(1, 0, 0);
    return base.mix(other, double.parse(mix.group(3)!) / 100);
  }
  final ok = RegExp(r'^oklch\(([\d.]+)(%?) ([\d.]+) ([\d.]+)(?: / ([\d.]+))?\)$').firstMatch(value);
  if (ok != null) {
    var l = double.parse(ok.group(1)!);
    if (ok.group(2) == '%') l /= 100;
    return Oklch(
      l,
      double.parse(ok.group(3)!),
      double.parse(ok.group(4)!),
      ok.group(5) == null ? 1 : double.parse(ok.group(5)!),
    );
  }
  throw FormatException('Unsupported color value', value);
}
